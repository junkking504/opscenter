import { chromium } from 'playwright';
import assert from 'node:assert/strict';
const browser=await chromium.launch({headless:true});
const page=await browser.newPage({viewport:{width:1280,height:720}});
let navigations=0;page.on('framenavigated',frame=>{if(frame===page.mainFrame())navigations++;});
await page.clock.install({time:new Date('2026-10-09T18:00:00Z')});
await page.route('**/*',route=>new URL(route.request().url()).hostname==='127.0.0.1'?route.continue():route.fulfill({status:204}));
await page.goto('http://127.0.0.1:3158/tests/aspect-ratio.html?workspace=Command');
await page.waitForSelector('.workspace');
await page.evaluate(()=>{const original=window.fetch;window.testRelease='a'.repeat(40);window.fetch=(input,init)=>String(input).includes('release-check')?Promise.resolve(new Response(null,{status:200,headers:window.testRelease?{'x-opscenter-release':window.testRelease}:{}})):original(input,init);});
await page.clock.runFor(61_000);assert.equal(await page.getByRole('status',{name:'Update ready'}).count(),0);
await page.evaluate(()=>{window.testRelease='b'.repeat(40);});await page.clock.runFor(61_000);
await page.getByRole('status',{name:'Update ready'}).waitFor();const count=navigations;
await page.clock.runFor(180_000);assert.equal(navigations,count,'Release changes must never auto-reload');
await page.getByRole('button',{name:'Later',exact:true}).click();await page.clock.runFor(61_000);assert.equal(await page.getByRole('status',{name:'Update ready'}).count(),0);
await page.evaluate(()=>{window.testRelease='';});await page.clock.runFor(61_000);assert.equal(navigations,count);
await page.evaluate(()=>{window.testRelease='c'.repeat(40);});await page.clock.runFor(61_000);await page.getByRole('status',{name:'Update ready'}).waitFor();
await Promise.all([page.waitForEvent('framenavigated'),page.getByRole('button',{name:'Refresh now',exact:true}).click()]);
assert.equal(navigations,count+1,'Only the explicit Refresh now click reloads');
await browser.close();console.log('Release toast, Later, missing headers and no automatic reload passed.');
