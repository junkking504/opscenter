import assert from 'node:assert/strict';
import {mkdir} from 'node:fs/promises';
import {chromium} from 'playwright';

const directory = process.env.ALERT_PREVIEW_OUTPUT || '/tmp/opscenter-crew-progress-preview';
await mkdir(directory,{recursive:true});
const browser = await chromium.launch({headless:true});
const errors = [];
try {
  const page = await browser.newPage({viewport:{width:1440,height:1000},deviceScaleFactor:1});
  page.on('pageerror',error => errors.push(error.message));
  await page.goto('http://127.0.0.1:3128/tests/crew-progress.html');
  await page.getByRole('heading',{name:'Operational updates',exact:true}).waitFor();
  assert.equal(await page.locator('.crew-job-card').count(),3);
  assert.equal(await page.locator('.crew-job-steps .missing').count(),1);
  await page.getByRole('button',{name:'View 1 photo',exact:true}).click();
  await page.getByRole('dialog').waitFor();
  await page.getByRole('button',{name:'Close photos'}).click();
  await page.screenshot({path:`${directory}/desktop.png`,fullPage:true});
  const firstJob = page.locator('.crew-job-card').filter({has:page.getByRole('link',{name:'JK1000001',exact:true})});
  const durationDetails = firstJob.getByRole('button',{name:'Duration: Recorded. Show details',exact:true});
  await durationDetails.focus();
  await page.keyboard.press('Enter');
  assert.equal(await firstJob.getByText('Recorded time on site.',{exact:true}).isVisible(),true,'Compact statuses retain keyboard-accessible evidence details');
  await firstJob.getByRole('button',{name:'Duration: Recorded. Hide details',exact:true}).click();
  assert.equal(await firstJob.getByText('Recorded time on site.',{exact:true}).count(),0);
  assert.match(await firstJob.locator('.crew-step-facts').first().innerText(),/8:05 AM[\s\S]*9:10 AM/,'Both visit times remain visible without opening details');
  await firstJob.getByRole('button',{name:'Show 2 updates'}).click();
  assert.deepEqual(await firstJob.locator('.crew-update-content header strong').allTextContents(),['Job Closed','Duration']);
  await firstJob.getByRole('button',{name:'Mark reviewed',exact:true}).first().click();
  assert.equal(await firstJob.locator('.crew-update').count(),2,'Review must retain the event in history');
  assert.equal(await firstJob.getByText('Reviewed',{exact:true}).count(),1);
  await firstJob.getByRole('button',{name:'Follow up in Control',exact:true}).first().click();
  assert.equal(await firstJob.getByText('Follow-up in Control',{exact:true}).count(),1);
  await firstJob.getByRole('button',{name:'Open record',exact:true}).first().click();
  assert.match(await page.getByRole('status').last().textContent(),/job-jk1000001/);
  await page.screenshot({path:`${directory}/timeline.png`,fullPage:true});
  await page.getByRole('combobox',{name:'Filter by truck'}).selectOption('Truck 3');
  assert.equal(await page.locator('.crew-job-card').count(),1);
  assert.equal(await page.getByRole('link',{name:'JK1000003',exact:true}).count(),1);
  await page.getByRole('button',{name:'Clear filters',exact:true}).click();
  await page.getByRole('searchbox',{name:'Search operational updates'}).fill('JK1000002');
  assert.equal(await page.locator('.crew-job-card').count(),1);
  await page.getByRole('button',{name:'Clear filters',exact:true}).click();
  await page.getByRole('button',{name:'Follow-up only',exact:true}).click();
  assert.equal(await page.locator('.crew-job-card').count(),1);
  await page.getByRole('button',{name:'Clear filters',exact:true}).click();
  await page.getByRole('button',{name:'All updates',exact:true}).click();
  assert.equal(await page.locator('.crew-update').count(),5);
  assert.equal(await page.locator('.crew-update-content header strong').first().textContent(),'Arrival');
  await page.getByRole('button',{name:'Simulate partial history'}).click();
  assert.match(await page.locator('.crew-source-notice').textContent(),/history is incomplete/);
  assert.equal(await page.getByRole('button',{name:'Mark reviewed',exact:true}).first().isEnabled(),true,'Known source updates remain actionable during partial history');
  await page.getByRole('button',{name:'Simulate disconnected sources'}).click();
  assert.match(await page.locator('.crew-source-notice').textContent(),/history is incomplete/);
  for (const button of await page.getByRole('button',{name:'Mark reviewed',exact:true}).all()) assert.equal(await button.isDisabled(),true);
  await page.getByRole('button',{name:'Reset preview'}).click();
  await page.getByRole('button',{name:'By truck & job',exact:true}).click();
  await page.setViewportSize({width:390,height:844});
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth),true,'Mobile must not overflow horizontally');
  await page.screenshot({path:`${directory}/mobile.png`,fullPage:true});
  assert.deepEqual(errors,[]);
  console.log(`Browser checks passed: grouping, chronological history, review retention, Control linkage, record action, search, truck/follow-up filters, incomplete sources, mobile overflow. Screenshots: ${directory}`);
} finally { await browser.close(); }
