import assert from 'node:assert/strict';
import { adjacentWorkspace, downwardIntent, horizontalIntent } from '../desktop-ui/lib/mobile-gestures';
const p=(x:number,y:number,at=0)=>({x,y,at});
assert.equal(horizontalIntent(p(200,100),p(90,110,300),390),1);
assert.equal(horizontalIntent(p(100,100),p(205,90,300),390),-1);
assert.equal(horizontalIntent(p(15,100),p(120,100,300),390),0,'browser edge-back reserved');
assert.equal(horizontalIntent(p(380,100),p(200,100,300),390),0,'both screen edges reserved');
assert.equal(horizontalIntent(p(200,100),p(176,100,300),390),0,'small swipe ignored');
assert.equal(horizontalIntent(p(200,100),p(90,190,300),390),0,'diagonal scroll ignored');
assert.equal(horizontalIntent(p(200,100),p(90,100,1000),390),0,'slow selection ignored');
assert.equal(downwardIntent(p(100,100),p(110,205,500)),true);
assert.equal(downwardIntent(p(100,100),p(205,205,500)),false);
assert.equal(downwardIntent(p(100,100),p(100,10,300)),false);
const order=['Command','Schedule','Krewe','Fleet','Marketing'];
assert.equal(adjacentWorkspace('Command',order,1),'Schedule');
assert.equal(adjacentWorkspace('Command',order,-1),undefined,'no wrap');
assert.equal(adjacentWorkspace('Fleet',order,1),'Marketing','permission-hidden Finance absent');
assert.equal(adjacentWorkspace('missing',order,1),undefined);
assert.equal(horizontalIntent(p(200,100),p(140,104,300),390),1,'short deliberate swipe accepted');
assert.equal(horizontalIntent(p(200,100),p(160,102,70),390),1,'quick flick accepted');
assert.equal(horizontalIntent(p(200,100),p(160,102,200),390),0,'short slow drag ignored');
assert.equal(horizontalIntent(p(200,100),p(160,132,70),390),0,'diagonal flick ignored');
console.log('Mobile gesture intent: 18 assertions passed');
