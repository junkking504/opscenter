import assert from 'node:assert/strict';
import { fileURLToPath } from 'node:url';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { createServer } from '../desktop-ui/node_modules/vite/dist/node/index.js';
import { chromium } from 'playwright';
const root=fileURLToPath(new URL('../',import.meta.url));
const output=process.env.MILEAGE_TEST_OUTPUT || fs.mkdtempSync(path.join(os.tmpdir(),'convoy-mileage-evidence-'));
fs.mkdirSync(output,{recursive:true});
const cache=fs.mkdtempSync(path.join(os.tmpdir(),'convoy-mileage-browser-'));
const server=await createServer({configFile:path.join(root,'desktop-ui/vite.opscenter.config.ts'),configLoader:'runner',cacheDir:cache,base:'/',server:{host:'127.0.0.1',port:0}});
let browser;
try {
 await server.listen();browser=await chromium.launch({headless:true});
 const page=await browser.newPage({viewport:{width:1440,height:1000}}),errors=[];
 page.on('pageerror',e=>{errors.push(e.message);console.log('PAGE',e.message)});page.on('console',msg=>{if(msg.type()==='error')console.log('CONSOLE',msg.text())});page.on('requestfailed',req=>console.log('REQUEST',req.url(),req.failure()));
 page.setDefaultTimeout(120000);
 await page.goto(`http://127.0.0.1:${server.httpServer.address().port}/tests/convoy.html`,{timeout:120000});
 const rows=page.locator('.clb-board tbody tr');
 await rows.first().waitFor();
 assert.equal(await rows.count(),9);
 const panel=page.locator('.convoy-truck-dashboard');
 const selectTruck=async number=>{
   await rows.filter({has:page.getByRole('button',{name:`Truck ${number}`,exact:true})}).click();
   assert.equal(await panel.count(),1);
   assert.match(await panel.locator('header').innerText(),new RegExp(`Truck ${number}`));
 };
 await selectTruck(1);
 assert.match(await panel.locator('.convoy-monthly-mileage').innerText(),/0 mi recorded/);
 assert.match(await panel.locator('.convoy-vin').innerText(),/JALC4W164M7000001/);
 assert.match(await panel.locator('.convoy-mileage strong').innerText(),/31,000 mi/);
 await selectTruck(7);
 assert.match(await panel.locator('.convoy-monthly-mileage').innerText(),/Not Yet Available/);
 await selectTruck(5);
 assert.match(await panel.locator('.convoy-vin').innerText(),/Not Yet Available/);
 assert.match(await panel.locator('.convoy-mileage').innerText(),/No mileage reading/);
 await selectTruck(2);
 assert.match(await panel.locator('.convoy-monthly-mileage').innerText(),/123.5 mi recorded/);
 assert.match(await panel.locator('.convoy-monthly-mileage').innerText(),/Oct 2026/);
 assert.match(await panel.locator('.convoy-vin').innerText(),/JALC4W164M7000002/);
 assert.match(await panel.locator('.convoy-mileage strong').innerText(),/61,000 mi/);
 await page.screenshot({path:path.join(output,'mileage-desktop.png'),fullPage:true});
 await page.getByRole('button',{name:'Operations & inspections'}).waitFor();
 assert.equal(await page.locator('.convoy-truck-dashboard').count(),1);
 const coverage=page.locator('.convoy-truck-dashboard .convoy-monthly-mileage details');
 assert.equal(await coverage.getByText(/days with trips/).isVisible(),false);
 await coverage.getByText('Mileage coverage',{exact:true}).click();
 assert.equal(await coverage.getByText(/days with trips.*Partial coverage/).isVisible(),true);
 assert.match(await page.locator('.convoy-truck-dashboard').innerText(),/Latest included trip: Oct 8/);
 assert.match(await page.locator('.convoy-truck-dashboard').innerText(),/Monthly mileage · Oct 2026/);
 await page.getByRole('button',{name:'Operations & inspections'}).click();
 await page.getByRole('dialog').waitFor();
 assert.match(await page.getByRole('dialog').locator('.convoy-monthly-mileage').innerText(),/123.5 mi recorded/);
 await page.getByRole('button',{name:'Close Fleet record'}).click();
 await page.setViewportSize({width:390,height:844});
 const monthly=page.locator('.convoy-truck-dashboard .convoy-monthly-mileage');
 await monthly.scrollIntoViewIfNeeded();
 const bounds=await monthly.boundingBox();assert.ok(bounds&&bounds.width<=390);
 await page.screenshot({path:path.join(output,'mileage-mobile.png'),fullPage:true});
 assert.deepEqual(errors,[]);console.log('Browser passed: all nine Overview rows, explicit zero, missing mileage, partial evidence, selected truck, drawer, 390px layout; no page errors.');
} finally {await browser?.close();await server.close();fs.rmSync(cache,{recursive:true,force:true});}
