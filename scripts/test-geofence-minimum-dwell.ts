import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import {trackedGeofenceVisits,readGeofenceEntries,geofenceTimelineAlerts,withoutNativeGeofenceDuplicates} from '../lib/linxup-geofence-alerts';
import {qualifiedGeofenceVisit} from '../lib/visit-tracking-agent';
import {runUnloadCostAgent} from '../lib/unload-cost-agent';
import {defaultDumpFeePolicy} from '../lib/dump-expenses';
import {buildGeofenceSlackNotifications} from '../lib/slack-alerts';
const date='2026-09-20', start=Date.parse(`${date}T15:00:00Z`),now=start+8*3600_000;
const at=(seconds:number)=>new Date(start+seconds*1000).toISOString();
const point=(seconds:number,name='EMR',truck='9')=>({truck_number:truck,geofence_name:name,occurred_at:at(seconds)});
const event=(seconds:number,type='entered',name='EMR',truck='9')=>({...point(seconds,name,truck),alert_type:`geofence_${type}`});
const project=(seconds:number,name='EMR')=>trackedGeofenceVisits(date,[],[event(0,'entered',name),event(seconds,'exited',name)],now);
for(const name of ['EMR','Gentilly','Warehouse','Customer zone']) for(const seconds of [0,61,299,300,301]) {
  const visits=project(seconds,name), qualifies=seconds>=300;
  assert.equal(qualifiedGeofenceVisit(visits[0]),qualifies,`${name}: ${seconds}s boundary`);
  const costs=runUnloadCostAgent(date,visits,[],defaultDumpFeePolicy,now);
  assert.equal(costs.unloads.length,qualifies && ['EMR','Gentilly'].includes(name)?1:0);
  assert.equal(costs.records.length,qualifies && name==='Gentilly'?1:0);
}
const lone=trackedGeofenceVisits(date,[],[event(0)],now);
assert.equal(qualifiedGeofenceVisit(lone[0]),false,'Clock age is not dwell');
const open=trackedGeofenceVisits(date,[point(0),point(150),point(300)],[],now);
assert.equal(qualifiedGeofenceVisit(open[0]),true,'Continuous GPS proves five minutes');
assert.equal(qualifiedGeofenceVisit(trackedGeofenceVisits(date,[point(0),point(600)],[],now)[0]),false,'Unobserved gap is not dwell');
const bounded=trackedGeofenceVisits(date,[point(0),point(150),point(300),point(3600,'Warehouse')],[],now);
assert.equal(qualifiedGeofenceVisit(bounded.find(v=>v.name==='EMR')!),true);
const shortBounded=trackedGeofenceVisits(date,[point(0),point(61),point(3600,'Warehouse')],[],now);
assert.equal(qualifiedGeofenceVisit(shortBounded.find(v=>v.name==='EMR')!),false,'Travel time in departure upper bound is not onsite time');
assert.equal(qualifiedGeofenceVisit(trackedGeofenceVisits(date,[],[event(0),event(150),event(600,'exited')],now)[0]),false,'Ambiguous native entries do not qualify');
const repeated=trackedGeofenceVisits(date,[],[event(0),event(300,'exited'),event(600),event(661,'exited')],now);
assert.equal(repeated.filter(qualifiedGeofenceVisit).length,1,'Each reentry qualifies independently');
assert.equal(qualifiedGeofenceVisit(trackedGeofenceVisits(date,[point(0),point(600,'Warehouse')],[event(0),event(700,'exited')],now).find(v=>v.name==='EMR')!),false,'Conflicting evidence cannot trigger effects');
const midnight=trackedGeofenceVisits(date,[],[{...event(0),occurred_at:'2026-09-20T04:58:00Z'},{...event(0,'exited'),occurred_at:'2026-09-20T05:03:00Z'}],now);
assert.equal(midnight.filter(qualifiedGeofenceVisit).length,1,'Chicago midnight retains five-minute visit');
const root=fs.mkdtempSync(path.join(os.tmpdir(),'geofence-dwell-')),original=process.env.OPSCENTER_DATA_DIR;
process.env.OPSCENTER_DATA_DIR=root;
try {
  const directory=path.join(root,'history/linxup/alerts');fs.mkdirSync(directory,{recursive:true});
  const file=path.join(directory,`linxup_alerts_${date}.json`);
  const write=(seconds:number)=>fs.writeFileSync(file,JSON.stringify({date,alerts:[event(0),event(seconds,'exited')]}));
  write(61);
  let source=readGeofenceEntries(date);
  assert.equal(source.rawEntries.length,1);assert.equal(source.rawNativeVisits[0].durationSeconds,61);
  assert.equal(source.trackedVisits.length,0);assert.equal(source.entries.length,0);assert.equal(source.visits.length,0);
  assert.equal(geofenceTimelineAlerts(date,source.arrivals,source.visits).length,0);
  assert.equal(buildGeofenceSlackNotifications(date,source.entries,source.nativeVisits).length,0);
  assert.equal(withoutNativeGeofenceDuplicates([{rawText:'Truck 9 at EMR',timestamp:at(30)},{rawText:'Truck 9 departed EMR',timestamp:at(70)}],source.rawEntries,source.rawNativeVisits).length,0,'Existing digest copies cannot resurrect a drive-by');
  write(300);source=readGeofenceEntries(date);
  assert.equal(source.trackedVisits.length,1);assert.equal(source.entries.length,1);assert.equal(source.visits.length,1);
  assert.equal(buildGeofenceSlackNotifications(date,source.entries,source.nativeVisits).length,2);
  const actual={id:'a'.repeat(32),date,truck:'Truck# 9',market:'477',kind:'dump' as const,transactionAt:at(61),location:'Gentilly',amount:44,receipt:'receipt',notify:false};
  assert.equal(runUnloadCostAgent(date,project(61,'Gentilly'),[actual],defaultDumpFeePolicy,now).actualTotal,44,'Actual receipt survives removal of a drive-by');
} finally {if(original===undefined)delete process.env.OPSCENTER_DATA_DIR;else process.env.OPSCENTER_DATA_DIR=original;fs.rmSync(root,{recursive:true,force:true});}
console.log('PASS five-minute geofence boundary, continuous evidence, gaps, repeated entries, midnight, conflicts, alerts, loads and actual expenses');
