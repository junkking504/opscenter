import { chromium } from 'playwright';
import assert from 'node:assert/strict';
const browser=await chromium.launch({headless:true});
const page=await browser.newPage({viewport:{width:1920,height:1080}});
const errors=[];page.on('pageerror',error=>errors.push(error.message));
await page.clock.install({time:new Date('2026-10-09T18:00:00Z')});
await page.route('**/*',route=>new URL(route.request().url()).hostname==='127.0.0.1'?route.continue():route.fulfill({status:204}));
await page.goto('http://127.0.0.1:3158/tests/aspect-ratio.html?workspace=Command&commandMap=1');
await page.getByRole('link',{name:'Shop TV',exact:true}).click();
await page.waitForSelector('.tv-ranking:not(.tv-ranking-head)');
assert.equal(await page.locator('.tv-ranking:not(.tv-ranking-head)').count(),5);
assert.equal(await page.locator('.page-rail,.appointment-closeout,.crew-today-actions').count(),0);
assert.ok((await page.locator('.tv-leaderboard').innerText()).includes('$160'));
await page.evaluate(()=>{window.tvReads=0;window.tvWrites=0;const original=window.fetch;window.fetch=async(input,init)=>{if(init?.method && !['GET','HEAD'].includes(init.method))window.tvWrites++;const response=await original(input,init);if(String(input).startsWith('/api/desktop/krewe')){window.tvReads++;const body=await response.json();body.members[7].revenue=1280;return Response.json(body);}return response;};});
await page.clock.runFor(31_000);
await page.waitForFunction(()=>document.querySelector('.tv-ranking:not(.tv-ranking-head)')?.textContent?.includes('Member 8'));
assert.ok(await page.evaluate(()=>window.tvReads>=1));assert.equal(await page.evaluate(()=>window.tvWrites),0);
assert.deepEqual(errors,[]);
assert.ok(await page.evaluate(()=>document.documentElement.scrollHeight<=innerHeight),'TV fits the wall display');
await browser.close();console.log('Shop TV top-five ranking, RPH, automatic read refresh, no writes and 1080p fit passed.');
