import assert from 'node:assert/strict';
import {mkdir} from 'node:fs/promises';
import {chromium} from 'playwright';

const directory = process.env.ALERT_PREVIEW_OUTPUT || '/tmp/opscenter-crew-progress-preview';
await mkdir(directory,{recursive:true});
const browser = await chromium.launch({headless:true});
const errors = [];
try {
  const page = await browser.newPage({viewport:{width:1440,height:1000},deviceScaleFactor:1});
  page.on('pageerror',error => errors.push(error.message));
  await page.goto(process.env.CREW_PROGRESS_PREVIEW_URL || 'http://127.0.0.1:3128/tests/crew-progress.html');
  await page.getByRole('heading',{name:'Operational updates',exact:true}).waitFor();
  const timeline = page.getByRole('region',{name:'All operational updates, newest first'});
  const labels = () => timeline.locator('.crew-update-label').allTextContents();
  const expected = ['Arrival','New Appointment','Krewe Summary','Job Completed'];
  assert.deepEqual(await labels(),expected,'All sources share one newest-first timeline; attendance stays between job updates');
  assert.equal(await page.locator('.crew-truck-group,.crew-other-updates,.crew-job-card').count(),0,'No separate truck, appointment, or other-update groups');
  assert.equal(await page.getByRole('button',{name:'By truck & job',exact:true}).count(),0);
  await page.getByRole('button',{name:'View 1 photo',exact:true}).click();
  await page.getByRole('dialog').waitFor();
  await page.getByRole('button',{name:'Close photos'}).click();
  const appointment = timeline.locator('.crew-update').filter({hasText:'New Appointment'});
  assert.match(await appointment.innerText(),/JK1000002[\s\S]*customer@example.invalid[\s\S]*Two queen mattresses[\s\S]*Use the side entrance/,'Appointment contact, items and pertinent notes remain visible');
  assert.match(await appointment.locator('.crew-event-header').innerText(),/^New Appointment[\s\S]*New Orleans[\s\S]*JK1000002[\s\S]*11:00 AM – 12:00 PM$/);
  assert.equal(await appointment.locator('.crew-event-job').getAttribute('href'),'/desktop?data=live&workspace=Schedule&scheduleView=board&scheduleDay=today&date=2026-09-07&appointment=102');
  assert.equal(await appointment.evaluate(element => getComputedStyle(element).backgroundColor),'rgba(250, 204, 21, 0.125)');
  assert.equal(await appointment.locator('.crew-territory-pill').evaluate(element => getComputedStyle(element).backgroundColor),'rgb(176, 210, 253)');
  const territoryPill = appointment.locator('.crew-territory-pill');
  await territoryPill.evaluate(element => element.className = 'crew-territory-pill crew-territory-northshore');
  assert.equal(await territoryPill.evaluate(element => getComputedStyle(element).backgroundColor),'rgb(250, 232, 255)');
  assert.equal(await territoryPill.evaluate(element => getComputedStyle(element).color),'rgb(17, 24, 39)');
  const duration = timeline.locator('.crew-update-completed');
  assert.match(await duration.innerText(),/8:05 AM[\s\S]*9:10 AM/,'Duration retains both confirmed times');
  assert.match(await duration.innerText(),/Follow up:[\s\S]*No uploaded photos/,'Latest appointment update keeps the missing-evidence action visible');
  const closed = timeline.locator('.crew-update-completed');
  assert.match(await closed.locator('.crew-event-header').innerText(),/^Job Completed[\s\S]*New Orleans[\s\S]*JK1000001[\s\S]*8:00 AM – 9:00 AM[\s\S]*Truck 2$/);
  assert.match((await closed.locator('.crew-completed-summary').innerText()).replace(/\s+/g,' '),/^C: Example customer \| D: Example driver \| N: Example navigator Load: \$450\.00 \(Half truck\) Payment: \$450\.00 \(Cash\)[\s\S]*On-site time: 65 min/);
  assert.equal(await closed.evaluate(element => getComputedStyle(element).backgroundColor),'rgba(34, 197, 94, 0.25)');
  await closed.getByRole('button',{name:'Mark reviewed',exact:true}).click();
  assert.deepEqual(await labels(),expected,'Review retains the event and chronology');
  assert.equal(await closed.getByText('Reviewed',{exact:true}).count(),1);
  await closed.getByRole('button',{name:'Follow up in Control',exact:true}).click();
  assert.equal(await closed.getByText('Follow-up in Control',{exact:true}).count(),1);
  await closed.getByRole('button',{name:'Open Control',exact:true}).click();
  assert.match(await page.getByRole('status').last().textContent(),/Control/);
  await closed.getByRole('button',{name:'Open record',exact:true}).click();
  assert.match(await page.getByRole('status').last().textContent(),/job-jk1000001/);
  await page.getByRole('button',{name:'Simulate estimate completed',exact:true}).click();
  const estimate = timeline.locator('.crew-update-completed');
  assert.match(await estimate.locator('.crew-event-header').innerText(),/^Estimate Completed[\s\S]*New Orleans[\s\S]*JK1000001[\s\S]*8:00 AM – 9:00 AM[\s\S]*Truck 2$/);
  assert.match((await estimate.locator('.crew-completed-summary').innerText()).replace(/\s+/g,' '),/Total: \$450\.00/);
  assert.equal(await estimate.getByText('Payment:',{exact:true}).count(),0,'Estimates show a total, not payment language');
  await page.getByRole('button',{name:'Reset preview'}).click();
  await page.screenshot({path:`${directory}/desktop.png`,fullPage:true});
  await page.getByRole('combobox',{name:'Filter by truck'}).selectOption('Truck 3');
  assert.deepEqual(await labels(),['Arrival']);
  assert.match(await timeline.innerText(),/JK1000003/);
  await page.getByRole('button',{name:'Clear filters',exact:true}).click();
  await page.getByRole('searchbox',{name:'Search operational updates'}).fill('JK1000002');
  assert.deepEqual(await labels(),['New Appointment']);
  await page.getByRole('button',{name:'Clear filters',exact:true}).click();
  await page.getByRole('button',{name:'Follow-up only',exact:true}).click();
  assert.deepEqual(await labels(),['Job Completed']);
  await page.getByRole('button',{name:'Clear filters',exact:true}).click();
  assert.deepEqual(await labels(),expected);
  await page.getByRole('button',{name:'Simulate partial history'}).click();
  assert.match(await page.locator('.crew-source-notice').textContent(),/history is incomplete/);
  assert.equal(await page.getByRole('button',{name:'Mark reviewed',exact:true}).first().isEnabled(),true,'Known source updates remain actionable during partial history');
  await page.getByRole('button',{name:'Simulate disconnected sources'}).click();
  assert.match(await page.locator('.crew-source-notice').textContent(),/history is incomplete/);
  for (const button of await page.getByRole('button',{name:'Mark reviewed',exact:true}).all()) assert.equal(await button.isDisabled(),true);
  await page.getByRole('button',{name:'Reset preview'}).click();
  await page.getByRole('button',{name:'Simulate unindexed updates'}).click();
  assert.deepEqual(await labels(),['Arrival','New Appointment','Truck Unloaded','Krewe Summary','Job Completed','Inspection'],'Source updates missing from appointment indexes are retained; timezone offsets sort by instant and unknown times sort last');
  await page.getByRole('button',{name:'Reset preview'}).click();
  await page.getByRole('button',{name:'Simulate warehouse entry'}).click();
  assert.deepEqual(await labels(),['Arrival','New Appointment','Geofence Entry','Krewe Summary','Job Completed'],'Native geofence entries interleave by occurrence time');
  const warehouse = timeline.locator('.crew-update').filter({hasText:'Geofence Entry'});
  assert.match(await warehouse.innerText(),/Junk King warehouse[\s\S]*Unchanged/,'Warehouse entry does not claim an unload');
  assert.equal(await warehouse.getByRole('button',{name:'Mark reviewed',exact:true}).count(),0,'Routine facility entry needs no review');
  await warehouse.getByRole('button',{name:'Open record',exact:true}).click();
  assert.match(await page.getByRole('status').last().textContent(),/workspace=Fleet/);
  await page.getByRole('button',{name:'Reset preview'}).click();
  await page.getByRole('button',{name:'Simulate clock-out pay',exact:true}).click();
  assert.deepEqual(await labels(),['Clock Out',...expected],'Final daily pay appears within one Clock Out alert');
  const shift = timeline.locator('.crew-update').filter({hasText:'Clock Out'});
  assert.match(await shift.innerText(),/6:10 PM[\s\S]*8.25[\s\S]*\$225.68[\s\S]*\$188.70[\s\S]*\$36.98[\s\S]*\$0.00/);
  assert.equal(await shift.getByRole('button',{name:'Mark reviewed',exact:true}).count(),0,'Routine attendance needs no review');
  await shift.getByRole('button',{name:'Open record',exact:true}).click();
  assert.match(await page.getByRole('status').last().textContent(),/crew\?date=2026-09-07/);
  await page.screenshot({path:`${directory}/clock-out-pay.png`,fullPage:true});
  await page.setViewportSize({width:390,height:844});
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth),true,'Mobile must not overflow horizontally');
  await page.screenshot({path:`${directory}/mobile.png`,fullPage:true});
  assert.deepEqual(errors,[]);
  console.log(`Browser checks passed: one mixed newest-first timeline, appointment details, review retention, Control linkage, record action, search, truck/follow-up filters, incomplete sources, mobile overflow. Screenshots: ${directory}`);
} finally { await browser.close(); }
