import assert from 'node:assert/strict';
import {calculateAppointmentCost,defaultCostInputs,appointmentCostOverheadAssumptions} from '../lib/appointment-cost-model';
import {appointmentCostPresentation} from '../lib/appointment-cost-presentation';
const travel={miles:40,minutes:60,inbound:'HQ',outbound:'HQ',note:'Synthetic',approximate:false};
const inputs={...defaultCostInputs,onsiteMinutes:60,disposal:30,extraCosts:15,revenueFeePercent:20};
const noFuel=calculateAppointmentCost(inputs,travel,null,40);
assert.equal(noFuel.attendanceKnownSubtotal,149);
assert.equal(noFuel.breakEvenKnownSubtotal,292.5);
assert.equal(noFuel.fuel,null);
assert.equal(noFuel.attendance,null);
assert.equal(noFuel.breakEven,null);
assert.equal(noFuel.minimumCharge,null);
assert.equal(noFuel.targetCharge,null);
assert.deepEqual(appointmentCostPresentation(noFuel,'To attend'),{amount:149,incomplete:true,missing:['Current fuel price']});
assert.deepEqual(appointmentCostPresentation(noFuel,'Break-even'),{amount:292.5,incomplete:true,missing:['Current fuel price']});
const gaps=calculateAppointmentCost({...inputs,disposal:null,onsiteMinutes:null},{...travel,miles:null,minutes:null},null,null);
assert.equal(gaps.attendanceKnownSubtotal,109);
assert.equal(gaps.breakEvenKnownSubtotal,155);
assert.deepEqual(gaps.attendanceMissing,['Route miles','Current fuel price','Travel time','Crew hourly cost']);
assert.equal(gaps.missing.length,6);
assert.equal(appointmentCostPresentation(gaps,'To attend').missing.length,4);
assert.equal(appointmentCostPresentation(gaps,'Break-even').missing.length,6);
const noDisposal=calculateAppointmentCost({...inputs,disposal:null},travel,4,40);
assert.deepEqual(appointmentCostPresentation(noDisposal,'Break-even'),{amount:275,incomplete:false,missing:['Disposal cost (enter 0 if none)']});
assert.deepEqual(appointmentCostPresentation(noDisposal,'To attend'),{amount:165,incomplete:false,missing:[]});
const complete=calculateAppointmentCost(inputs,travel,4,40);
assert.equal(complete.attendance,complete.attendanceKnownSubtotal);
assert.equal(complete.breakEven,complete.breakEvenKnownSubtotal);
assert.equal(appointmentCostPresentation(complete,'Break-even').incomplete,false);
const zero=calculateAppointmentCost({...defaultCostInputs,overhead:0,onsiteMinutes:0,disposal:0},{...travel,miles:0,minutes:0},4,40);
assert.equal(appointmentCostPresentation(zero,'Break-even').amount,0);
assert.equal(zero.minimumCharge,1);
for(const bad of [NaN,Infinity,-1]) {
 const result=calculateAppointmentCost(inputs,{...travel,miles:bad},4,40);
 assert.equal(result.fuel,null);
 assert.equal(result.attendance,null);
 assert.equal(result.attendanceKnownSubtotal,149);
}
const invalid=calculateAppointmentCost({...inputs,revenueFeePercent:100},travel,4,40);
assert.equal(invalid.attendanceKnownSubtotal,null);
assert.equal(invalid.breakEvenKnownSubtotal,null);
assert.equal(appointmentCostPresentation(invalid,'To attend').amount,null);
const failed={attendance:null,breakEven:null,breakEvenBeforeDisposal:null,missing:['Cost sources unavailable']};
assert.equal(appointmentCostPresentation(failed,'To attend').amount,null);
assert.equal(appointmentCostPresentation(undefined,'To attend').amount,null);
assert.equal(appointmentCostPresentation({...failed,missing:['Current fuel price']},'Break-even').amount,null);
console.log('Incomplete appointment cost math and shared card presentation passed (synthetic only).');

assert.match(appointmentCostOverheadAssumptions({...defaultCostInputs,fuelPrice:4})[0],/original inclusions unverified/);
assert.deepEqual(appointmentCostOverheadAssumptions({...defaultCostInputs,overhead:125}),[]);
