import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { randomUUID } from 'node:crypto';
import { spawnSync } from 'node:child_process';
import { buildPodiumReviewNameSuggestionMap, buildPodiumAppointmentMatcher, podiumInviteNameReferences } from '../lib/podium-review-attribution';
import { assignPodiumReviewToAppointment, readPodiumReviewAssignments, savePodiumHighConfidenceMatches, undoPodiumReviewAutoMatch } from '../lib/podium-review-assignments';

const root = fs.mkdtempSync(path.join(os.tmpdir(), 'review-signals-'));
process.env.OPSBOT_DATA_DIR = root;
process.env.PODIUM_REVIEW_ASSIGNMENT_STORE = path.join(root, 'operator/podium_review_assignments.json');
process.env.OPSCENTER_DESKTOP_COMMERCIAL_DIR = path.join(root, 'receipts');
const store = process.env.PODIUM_REVIEW_ASSIGNMENT_STORE;
const base = { job_status: 'Completed', appointment_type: 'Job', territory: 'Fixture Bay', driver_name: 'Eugene Fiction' };
const job = (id: string, extra: Record<string, unknown> = {}) => ({ ...base, appt_id: id, job_id: `JKTEST${id}`, customer_name: 'Jane Doe', completed_at: '2024-05-20T15:00:00Z', ...extra });
const input = { uid: 'review', authorName: 'Jane Doe', createdAt: '2024-05-20T22:00:00Z', locationName: 'Junk King Fixture Bay', body: '' };
const write = (file: string, value: unknown) => { const dest = path.join(root, file); fs.mkdirSync(path.dirname(dest), { recursive: true }); fs.writeFileSync(dest, JSON.stringify(value)); };
const metrics = (rows: Record<string, unknown>[], date = '2024-05-20') => write(`processed/daily_metrics_${date}.json`, { appointments: rows });
const rank = (changes = {}) => buildPodiumReviewNameSuggestionMap(root, [{ ...input, ...changes }]).review;
try {
  metrics([job('1')]);
  assert.equal(rank()[0].score, 85);
  assert.equal(rank()[0].confidence, 'High');
  assert.equal(rank({ authorName: 'Jane' })[0].score, 50, 'one token is partial, never full identity');
  assert.equal(rank({ authorName: 'Jane' })[0].confidence, 'Medium');
  assert.equal(rank({ authorName: 'Unknown' })[0].confidence, 'Low');
  assert.equal(rank({ authorName: 'Jake Wrong' })[0].matchKind, 'timing', 'one fuzzy first name is not a full-name variation');
  metrics([job('1', { customer_name: 'James Doe' })]);
  assert.equal(rank()[0].matchKind, 'partial_name', 'one matching surname remains partial');
  metrics([job('1', { customer_name: 'Jane J' })]);
  assert.equal(rank({ authorName: 'J' })[0].confidence, 'Low', 'a lone initial cannot establish identity');
  metrics([job('1'), job('2')]);
  assert.equal(rank()[0].confidence, 'Medium', 'ties block High');
  metrics([job('1'), job('2', { customer_name: 'Jane Other', appointment_notes: 'Oakridge storage' })]);
  assert.equal(rank({ body: 'Oakridge storage' })[0].confidence, 'Medium', 'margin uses whole pool before low truncation');
  metrics([job('1', { completed_at: '2024-05-20T23:00:00Z' }), job('2', { job_status: 'Not completed' }), job('3', { appointment_type: 'Estimate' }), job('4', { driver_name: '' }), job('5', { completed_at: '' })]);
  assert.deepEqual(rank(), [], 'future, not-complete, estimate, crewless and same-day unknown excluded');
  metrics([job('1', { completed_at: '05/20/2024 4:00:00 PM' })]);
  assert.equal(rank()[0].confidence, 'High', 'Chicago PM parsing');
  metrics([job('1', { completed_at: '05/20/2024 6:00:00 PM' })]);
  assert.deepEqual(rank(), [], 'Chicago completion after review excluded');
  metrics([job('1', { completed_at: '2024-05-01T15:00:00Z' }), job('2', { customer_name: 'Jane Else', completed_at: '2024-05-19T15:00:00Z' })]);
  assert.deepEqual(rank().map(c => c.appointmentId), ['2'], 'recent Medium prevents widening');
  metrics([job('1', { completed_at: '2024-05-01T15:00:00Z' }), job('2', { customer_name: 'Unrelated Person' })]);
  assert.equal(rank()[0].appointmentId, '1', 'widen if recent pool is only Low');
  assert.equal(rank()[0].confidence, 'Medium', 'old identity cannot auto-save');
  metrics([job('1', { customer_name: 'Unknown Person', completed_at: '2024-05-06T15:00:00Z' })]);
  assert.equal(rank({ body: 'Thanks to Gene for the help' })[0].score, 23, 'crew boost plus day-14 timing');
  metrics([job('1', { customer_name: 'Unknown Person', completed_at: '2024-05-05T15:00:00Z' })]);
  assert.deepEqual(rank({ body: 'Thanks to Gene for the help' }), [], 'crew and territory alone outside 14 days never suggest');
  metrics([job('1', { customer_name: 'Unrelated Person', additional_crew: ['Michael Fiction', 'Zach Fiction'] })]);
  assert.equal(rank({ body: 'Thanks to Eugene, Mike and Zach for helping.' })[0].score, 60, 'crew capped at 25');
  assert.equal(rank({ body: 'Thanks to Eugene, Mike and Zach for helping.' })[0].confidence, 'Medium', 'no identity');
  metrics(Array.from({ length: 8 }, (_, index) => job(String(index), { customer_name: 'Unrelated Person' })));
  assert.equal(rank().length, 3, 'at most three Low');
  metrics([job('1', { customer_name: 'Unrelated Person', customerEmail: 'jdoe123@example.invalid', appointment_notes: 'Oakridge storage warehouse facility', service_address: '11 Example St' })]);
  assert.equal(rank({ body: 'Oakridge storage warehouse facility' })[0].score, 90, 'context cap 20, surname email handle 35');
  const pii = JSON.stringify(rank({ body: 'Oakridge storage warehouse facility' }));
  assert.ok(!pii.includes('jdoe123') && !pii.includes('11 Example') && !pii.includes('Oakridge'));
  assert.equal(rank({ body: 'Excellent junk removal, great crew, professional service.' })[0].score, 70, 'generic words do not overlap');
  metrics([job('1', { customerEmail: 'notmatching@example.invalid' })]);
  const invite = { uid: 'invite', customerName: 'Jane Doe', channelIdentifier: '', locationUid: 'loc' };
  assert.equal(rank({ invite })[0].score, 145);
  const references = podiumInviteNameReferences(root, { ...input, invite });
  assert.deepEqual(references, ['1']);
  assert.equal(rank({ inviteNameReferences: references })[0].score, 145);
  assert.deepEqual(podiumInviteNameReferences(root, { ...input, invite: { ...invite, customerName: 'Someone Else' } }), []);
  // The raw snapshot enriches only matching appointment + job identities.
  metrics([job('1', { completed_at: '', customer_name: 'Unrelated Person' })]);
  write('history/junkware/junkware_2024-05-20_raw.json', { completed: [job('1', { customer_name: 'Unrelated Person', customerEmail: 'jdoe123@example.invalid', appointment_notes: 'Oakridge storage' })] });
  assert.equal(rank({ body: 'Oakridge storage' })[0].confidence, 'High');
  write('history/junkware/junkware_2024-05-20_raw.json', { completed: [job('1', { job_id: 'JKOTHER', completed_at: '2024-05-20T15:00:00Z' })] });
  assert.deepEqual(rank(), [], 'mismatched raw identity not used');
  fs.writeFileSync(path.join(root, 'history/junkware/junkware_2024-05-20_raw.json'), '{broken');
  assert.deepEqual(rank(), [], 'corrupt enrichment never yields a partial-pool High');
  fs.unlinkSync(path.join(root, 'history/junkware/junkware_2024-05-20_raw.json'));
  metrics([job('1', { customerEmail: 'jane1234567890@example.invalid', customer_phone: '2255550100' })]);
  const exact = buildPodiumAppointmentMatcher(root)(input.createdAt, { ...invite, channelIdentifier: 'jane1234567890@example.invalid' });
  assert.equal(exact.matchMethod, 'exact_email', 'digits in email must not become a phone');
  assert.equal(buildPodiumAppointmentMatcher(root)('2024-05-20T12:00:00Z', { ...invite, channelIdentifier: '2255550100' }).status, 'unmatched');
  delete process.env.PODIUM_REVIEW_HIGH_AUTO_SAVE;
  assert.equal(savePodiumHighConfidenceMatches(root, [input]), 0);
  assert.ok(!fs.existsSync(store), 'default-off does not even create store');
  process.env.PODIUM_REVIEW_HIGH_AUTO_SAVE = 'true';
  assert.equal(savePodiumHighConfidenceMatches(root, [{ ...input, attribution: exact }]), 0, 'preserve exact');
  assert.equal(savePodiumHighConfidenceMatches(root, [input]), 1);
  assert.equal(savePodiumHighConfidenceMatches(root, [input]), 0, 'idempotent');
  assert.equal(readPodiumReviewAssignments()[0].attribution.matchMethod, 'inferred_high');
  assert.ok(!/Jane|Doe|2255550100|example.invalid|customerEmail/.test(fs.readFileSync(store, 'utf8')), 'saved attribution has no customer PII');
  const { buildPodiumGoogleReviewsViewFromData } = require('../lib/podium-reviews') as typeof import('../lib/podium-reviews');
  const exactSnapshot = { version: 1 as const, source: 'podium_api' as const, fetchedAt: input.createdAt, locations: [{ uid: 'loc', name: input.locationName, address: '', averageRating: 5, reviewCount: 1, reviews: [{ ...input, rating: 5, url: '', updatedAt: input.createdAt, needsResponse: false, responseCount: 0, attribution: exact }] }] };
  assert.equal(buildPodiumGoogleReviewsViewFromData(exactSnapshot, []).locations[0].reviews[0].attribution?.matchMethod, 'exact_email', 'exact source takes precedence over saved inference');
  assert.equal(undoPodiumReviewAutoMatch(input.uid, 'synthetic-manager'), true);
  assert.equal(buildPodiumGoogleReviewsViewFromData(exactSnapshot, []).locations[0].reviews[0].attribution?.matchMethod, 'manual_unassigned', 'manager undo wins even over a later exact snapshot');
  assert.equal(savePodiumHighConfidenceMatches(root, [input]), 0, 'undo survives later runs');
  assert.equal(readPodiumReviewAssignments()[0].attribution.matchMethod, 'manual_unassigned');
  assignPodiumReviewToAppointment({ reviewUid: input.uid, appointmentReference: '1', assignedBy: 'synthetic-manager' });
  assert.equal(savePodiumHighConfidenceMatches(root, [input]), 0, 'manager always wins');
  assert.equal(undoPodiumReviewAutoMatch(input.uid, 'synthetic-manager'), false, 'undo cannot remove manual');
  // Cross-process contention uses the same store lock for automatic and manual.
  fs.mkdirSync(`${store}.lock`);
  const child = spawnSync(process.execPath, ['--import', 'tsx', '-e', "const m=require('./lib/podium-review-assignments');try{m.assignPodiumReviewToAppointment({reviewUid:'other',appointmentReference:'1',assignedBy:'fake'});process.exit(2)}catch{process.exit(0)}"], { cwd: process.cwd(), env: process.env, encoding: 'utf8' });
  assert.equal(child.status, 0);
  assert.throws(() => savePodiumHighConfidenceMatches(root, [{ ...input, uid: 'other' }]), /in progress/);
  fs.rmdirSync(`${store}.lock`);
  // Desktop undo uses the same role/version/idempotent receipt path as confirms.
  const { readDesktopMarketing, updateDesktopMarketing } = require('../lib/desktop-marketing') as typeof import('../lib/desktop-marketing');
  const snapshot = { version: 1, source: 'podium_api', fetchedAt: input.createdAt, locations: [{ uid: 'loc', name: input.locationName, address: '', averageRating: 5, reviewCount: 1, reviews: [{ ...input, authorName: input.authorName, rating: 5, url: '', updatedAt: input.createdAt, needsResponse: false, responseCount: 0 }] }] };
  write('podium-google-reviews/current.json', snapshot);
  fs.unlinkSync(store);
  savePodiumHighConfidenceMatches(root, [input]);
  const actor = { email: 'synthetic-manager', role: 'manager' as const };
  const current = readDesktopMarketing('2024-05-20', actor.role).reviews[0];
  assert.equal(current.attribution?.matchMethod, 'inferred_high');
  const operation = { requestId: randomUUID(), date: '2024-05-20', action: 'review.undo' as const, recordId: input.uid, expectedVersion: current.version, values: {} };
  assert.throws(() => updateDesktopMarketing(operation, { ...actor, role: 'operator' }), /Manager/);
  assert.throws(() => updateDesktopMarketing({ ...operation, expectedVersion: '0'.repeat(64) }, actor), /record changed/);
  assert.equal(updateDesktopMarketing(operation, actor).status, 'verified');
  assert.equal(updateDesktopMarketing(operation, actor).status, 'verified', 'undo receipt is replay-safe');
  assert.equal(readDesktopMarketing('2024-05-20', actor.role).reviews[0].attribution?.status, 'unmatched');
  assert.equal(savePodiumHighConfidenceMatches(root, [input]), 0);
  fs.writeFileSync(store, '{broken');
  assert.throws(() => savePodiumHighConfidenceMatches(root, [input]), /unreadable/);
  assert.equal(fs.readFileSync(store, 'utf8'), '{broken', 'corrupt store never overwritten');
  console.log('PASS scoring, windows, completion times, source enrichment, privacy, default-off, precedence, shared lock and receipt-backed undo.');
} finally { fs.rmSync(root, { recursive: true, force: true }); }
