import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { randomUUID } from 'node:crypto';
import { INSPECTION_SECTIONS } from '../lib/truck-inspection';
import { connectInspectionPhone, submitTruckInspection, correctInspectionTruck } from '../lib/truck-inspection-store';
import { inspectionTimelineAlert, readInspectionTimeline, mergeInspectionTimeline } from '../lib/truck-inspection-updates';
import { inspectionSlackNotification } from '../lib/truck-inspection-notifications';
import { operationalUpdatePreview } from '../desktop-ui/lib/operational-update-preview';
import { desktopAlertHref } from '../desktop-ui/lib/desktop-links';
import { commandAlertWorkItemForSource } from '../lib/command-alert-workflow';
import type { DesktopAlert } from '../desktop-ui/lib/live-contract';

const root = fs.mkdtempSync(path.join(os.tmpdir(), 'inspection-updates-'));
process.env.OPS_TRUCK_INSPECTION_DIR = path.join(root, 'reports');
process.env.SLACK_OPSCENTER_STATE_FILE = path.join(root, 'delivery.json');
const originalFetch = globalThis.fetch;
globalThis.fetch = async () => { throw new Error('Unexpected network request'); };
try {
  const now = new Date('2026-10-26T12:34:00Z');
  const device = connectInspectionPhone('a'.repeat(64), now).device;
  const input = (startedAt = '2026-10-26T12:30:00Z') => ({requestId:randomUUID(),truck:'Truck 9',inspector:'Fixture Inspector',initials:'FI',odometer:'1234',fuel:'1/2',loadLevel:'1/4',startedAt,answers:INSPECTION_SECTIONS.map(s=>({id:s.id,status:'good' as const,notes:''})),status:'clear' as const,notes:'',photos:[]});
  const report = submitTruckInspection(input(), device, now);
  const second = submitTruckInspection(input(), device, new Date('2026-10-26T12:35:00Z'));
  const late = submitTruckInspection(input('2026-10-25T12:30:00Z'), device, now);
  const previous = submitTruckInspection(input('2026-10-25T12:30:00Z'), device, new Date('2026-10-26T04:59:00Z'));
  const clear = inspectionTimelineAlert(report);
  assert.equal(clear.id, inspectionSlackNotification(report).fingerprint);
  assert.equal(clear.needsAction, false);
  assert.equal(clear.timestamp, report.receivedAt);
  for (const status of ['reported','stop'] as const) assert.equal(inspectionTimelineAlert({...report,status}).needsAction,true);
  assert.match(inspectionTimelineAlert({...report,status:'stop'}).next,/Do not operate/);
  const notes = inspectionTimelineAlert({...report,notes:'General note',answers:report.answers.map((a,i)=>({...a,notes:i===0?'Marked good but has a note':''}))});
  assert.equal(notes.needsAction,true);
  assert.ok(notes.facts.some(f=>f.value==='General note'));
  assert.ok(notes.facts.some(f=>f.value==='Marked good but has a note' && f.label.includes('marked Good')));
  assert.equal(inspectionTimelineAlert({...report,answers:report.answers.map((a,i)=>({...a,status:i===0?'problem':'good'}))}).needsAction,true);
  const desktop: DesktopAlert = {...clear,source:clear.source!,priority:'watch',detail:'',action:'Open Source',context:clear.next,workflowState:'active',version:0};
  assert.equal(operationalUpdatePreview(desktop),'Fixture Inspector · No problems');
  assert.equal(desktopAlertHref(desktop,{date:'2026-10-26'},'https://ops.junk-king.app'),clear.href);
  assert.match(inspectionTimelineAlert(late).href,/date=2026-10-25/);
  assert.equal(readInspectionTimeline('2026-10-26').alerts.length,3,'Receipt day includes late drafts and distinct reports');
  assert.equal(readInspectionTimeline('2026-10-26').alerts[0].id,inspectionTimelineAlert(second).id);
  assert.deepEqual(readInspectionTimeline('2026-10-25').alerts.map(a=>a.id),[inspectionTimelineAlert(previous).id],'Chicago midnight, historical history independent of current date');
  assert.equal(readInspectionTimeline('2026-10-24').complete,true);
  assert.equal(readInspectionTimeline('2026-10-24').alerts.length,0);
  const broken = readInspectionTimeline('2026-10-26',date=>{if(date==='2026-10-25')throw Error('unreadable');return date==='2026-10-26'?[report]:[];});
  assert.equal(broken.complete,false);assert.equal(broken.alerts.length,1);
  fs.writeFileSync(process.env.SLACK_OPSCENTER_STATE_FILE!,JSON.stringify({notificationMessages:{[clear.id]:{channelId:'C123',ts:'123.456'}}}));
  const native = readInspectionTimeline('2026-10-26').alerts.find(a=>a.id===clear.id)!;
  assert.deepEqual(native.sourceMessageIds,['C123:123.456']);
  const slack = {...clear,id:'C123:123.456',source:'Slack',label:'Fleet Update',sourceMessageIds:['old-copy']};
  const unrelated = {...slack,id:'other-inspection',eventFingerprint:'other'};
  const merged = mergeInspectionTimeline([slack,unrelated],[native]);
  assert.equal(merged.length,2);
  assert.ok(merged[1].sourceMessageIds?.includes('old-copy'));
  const work = {entity:{id:slack.id},status:'acknowledged'} as Parameters<typeof commandAlertWorkItemForSource>[0][number];
  assert.equal(commandAlertWorkItemForSource([work],merged[1]),work);
  assert.equal(mergeInspectionTimeline([unrelated],[native,inspectionTimelineAlert(second)]).length,3);
  fs.writeFileSync(process.env.SLACK_OPSCENTER_STATE_FILE!,'broken');
  assert.equal(readInspectionTimeline('2026-10-26').alerts.length,3,'Delivery ledger failure never hides native reports');
  correctInspectionTruck({deviceId:report.deviceId,requestId:report.requestId,expectedTruck:'Truck 9',truck:'Truck 4',actor:'fixture',reason:'Correction fixture'},now);
  const corrected = readInspectionTimeline('2026-10-26').alerts.find(a=>a.id===clear.id)!;
  assert.equal(corrected.truck,'Truck 4');assert.equal(corrected.id,clear.id);
  assert.ok(corrected.facts.some(f=>f.label==='Truck' && f.value==='Truck 4'));
  assert.equal(JSON.stringify(corrected).includes('data:image'),false);
  console.log('PASS native inspection history: offline reads, receipt days, late drafts, notes/status, corrections, exact dedup, workflow aliases, report navigation and source failure.');
} finally { globalThis.fetch = originalFetch; fs.rmSync(root,{recursive:true,force:true}); }
